import AppKit

/// Every item and type on the pasteboard, so it can be put back exactly.
struct PasteboardSnapshot: Equatable, Sendable {
    var items: [[String: Data]]

    static let empty = PasteboardSnapshot(items: [])
}

/// Pasteboard abstraction so output and clipboard-restore logic is testable.
@MainActor
protocol PasteboardClient: AnyObject {
    var changeCount: Int { get }
    func string() -> String?
    func setString(_ string: String)
    /// Writes a string marked as transient, so clipboard managers ignore it.
    func setTransientString(_ string: String)
    func snapshot() -> PasteboardSnapshot
    func restore(_ snapshot: PasteboardSnapshot)
}

@MainActor
final class SystemPasteboard: PasteboardClient {
    /// nspasteboard.org markers honoured by clipboard managers.
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let pasteboard: NSPasteboard

    init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int { pasteboard.changeCount }

    func string() -> String? { pasteboard.string(forType: .string) }

    func setString(_ string: String) {
        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
    }

    func setTransientString(_ string: String) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
    }

    func snapshot() -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [String: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type.rawValue] = data }
            }
            return types
        }
        return PasteboardSnapshot(items: items)
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
